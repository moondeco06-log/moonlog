# 章を組み立てる関数(ドラフト・確認用)
# ============================================================
def build_work_chapter(sun_sign, mars_sign, mc_sign, jupiter_sign, saturn_sign, current_age):
    """
    仕事章のHTMLテキストを生成する
    sun_sign, mars_sign, mc_sign, jupiter_sign, saturn_sign: "Ari", "Tau" など
    current_age: int (年齢)
    """
    # フェーズ判定
    if current_age < 20:
        current_phase = "10s"
    elif current_age < 30:
        current_phase = "20s"
    elif current_age < 40:
        current_phase = "30s"
    elif current_age < 50:
        current_phase = "40s"
    elif current_age < 60:
        current_phase = "50s"
    else:
        current_phase = "60s_plus"

    parts = []
    parts.append("# 💼 第1章：仕事・天職\n\n")
    parts.append("## 1. あなたの仕事観の核\n")
    parts.append(WORK_SUN_CORE[sun_sign] + "\n\n")
    parts.append("## 2. 何で頭角を現すか\n")
    parts.append(WORK_MARS_STYLE[mars_sign] + "\n\n")
    parts.append("## 3. 社会的な天職の方向\n")
    parts.append(WORK_MC_VOCATION[mc_sign] + "\n\n")
    parts.append("## 4. 仕事で気をつけたいクセ\n")
    parts.append(WORK_SUN_CAUTION[sun_sign] + "\n\n")
    parts.append("## 5. 人生フェーズマップ — 仕事人生の地図\n\n")
    for phase in ["10s", "20s", "30s", "40s", "50s", "60s_plus"]:
        marker = "✦ " if phase == current_phase else ""
        current_label = "（← 今ここ）" if phase == current_phase else ""
        parts.append(f"{marker}**{phase}**{current_label}\n")
        parts.append(WORK_PHASE_MAP[phase] + "\n\n")
    parts.append("**あなたの場合：**\n")
    parts.append(WORK_PHASE_JUPITER_OVERLAY[jupiter_sign] + "\n")
    parts.append(WORK_PHASE_SATURN_OVERLAY[saturn_sign] + "\n\n")
    parts.append("## 6. だから働いていい\n")
    parts.append(WORK_SUN_PUSH[sun_sign] + "\n")
    return "".join(parts)


